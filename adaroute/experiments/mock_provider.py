import asyncio
import random

from adaroute.schemas import RequestContext


class MockProvider:
    def __init__(self, replica_id: str, base_latency_ms: float = 100):
        self.replica_id = replica_id
        self.base_latency_ms = base_latency_ms

    async def execute(self, request: RequestContext) -> dict:
        # Simulate network & generation delay
        await asyncio.sleep(self.base_latency_ms / 1000.0)
        
        # Simulate generated output tokens
        output_tokens = max(1, int(random.gauss(request.estimated_output_tokens, 5)))
        
        return {
            "content": f"Mock response generated by {self.replica_id} for task: {request.task_type}",
            "replica_id": self.replica_id,
            "output_tokens": output_tokens
        }
